# Function without parameters: hardcoded greeting logic
def hello():
    print("Hello")

# Prompts user for input and calls hello(), printing name separately
name = input("What's your name? ")
hello()
print(name)

# A function is a block of organized, reusable code that is used to perform a single, related action.
# Functions provide better modularity for your application and a high degree of code reusing.
# Modularity is the practice of splitting a large program into small, independent pieces.
# Functions are defined with specific syntax and can take parameters as input and return values as output.